import { test, expect } from '@playwright/test';

test('the calculator updates from both probabilities and keeps them when closed', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 });
  await page.goto('learn/games/');
  const widget = page.getByRole('region', { name: 'Hidden Coin payoff calculator' });
  const summary = widget.locator('summary');
  const alice = widget.getByRole('spinbutton', { name: 'Alice hides in red' });
  const bob = widget.getByRole('spinbutton', { name: 'Bob picks red' });
  const payoff = widget.getByRole('status');
  await expect(alice).toBeHidden();
  await summary.press('Enter');
  await expect(alice).toBeEnabled();
  await expect(payoff).toContainText('$0.75');
  await alice.fill('1');
  await bob.fill('1');
  await expect(payoff).toContainText('$2.00');
  await bob.fill('0');
  await expect(payoff).toContainText('$0.00');
  await alice.fill('0');
  await expect(payoff).toContainText('$1.00');
  await alice.fill('0.333333333');
  await bob.fill('0.9');
  await expect(payoff).toContainText('$0.667');
  await bob.fill('1.1');
  await expect(bob).toHaveAttribute('aria-invalid', 'true');
  await expect(payoff).toContainText('—');
  await bob.fill('0.9');
  await summary.press('Enter');
  await expect(payoff).toBeHidden();
  await summary.press('Enter');
  await expect(alice).toHaveValue('0.333333333');
  await expect(payoff).toContainText('$0.667');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320);
});

test('the hider reveals the previous hide and tracks expected regret across rounds', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 });
  await page.addInitScript(() => { Math.random = () => 0.1; });
  await page.goto('learn/games/');
  const widget = page.getByRole('region', { name: 'Play against the MWU hider' });
  const summary = widget.locator('summary');
  const red = widget.getByRole('button', { name: 'Pick red' });
  const blue = widget.getByRole('button', { name: 'Pick blue' });
  const feedback = widget.getByRole('status');
  const regret = widget.getByText('Alice’s expected regret', { exact: true }).locator('..').locator('dd');
  const trend = widget.getByRole('img', { name: /Alice’s cumulative expected regret through round/ });
  await expect(red).toBeHidden();
  await summary.press('Enter');
  await expect(red).toBeEnabled();
  await expect(widget.getByText('50%', { exact: true })).toHaveCount(2);
  await expect(regret).toHaveText('$0.00');
  await expect(trend).toBeHidden();
  await red.press('Enter');
  await expect(feedback).toContainText('Alice hid in red');
  await expect(feedback).toContainText('$2.00 earned');
  await expect(widget.getByText('37.8%', { exact: true })).toBeVisible();
  await expect(regret).toHaveText('$1.00');
  await expect(trend).toHaveAccessibleName('Alice’s cumulative expected regret through round 1');
  await summary.press('Enter');
  await expect(blue).toBeHidden();
  await summary.press('Enter');
  await expect(widget.getByText('Round 2', { exact: true })).toBeVisible();
  await expect(regret).toHaveText('$1.00');
  await blue.press('Enter');
  await expect(feedback).toContainText('$0.00 earned');
  await expect(widget.getByText('43.8%', { exact: true })).toBeVisible();
  await expect(regret).toHaveText('$0.62');
  await expect(trend).toHaveAccessibleName('Alice’s cumulative expected regret through round 2');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320);
  await widget.getByRole('button', { name: 'Reset' }).press('Enter');
  await expect(widget.getByText('Round 1', { exact: true })).toBeVisible();
  await expect(widget.getByText('50%', { exact: true })).toHaveCount(2);
  await expect(regret).toHaveText('$0.00');
  await expect(trend).toBeHidden();
});
